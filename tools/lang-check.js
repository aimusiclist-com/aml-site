#!/usr/bin/env node
/* tools/lang-check.js — 언어팩 검사 (Node만 있으면 됨. 설치할 것 없음)
 * -----------------------------------------------------------------------------
 * 사용법 (개인사이트 폴더에서):
 *   node tools/lang-check.js              모든 언어팩 검사
 *   node tools/lang-check.js ko           한 언어만 검사
 *   node tools/lang-check.js --template fr   새 언어 fr 의 빈 틀(영어 문장 그대로)을 화면에 출력
 *        → node tools/lang-check.js --template fr > public/_app/lang/fr.js  로 파일을 만들 수 있다
 *
 * 검사 내용
 *   ✗ 빠진 키      : 영어(strings.js)에는 있는데 언어팩에 없는 키 (화면에는 영어로 보임)
 *   ✗ 모르는 키    : 영어에 없는 키 (키 이름을 잘못 바꾼 경우가 대부분)
 *   ✗ 변수 다름    : {name} 같은 변수가 영어와 다름 (빠졌거나 번역됨)
 *   ✗ 빈 문장
 *   ✗ 목록 누락    : lang/{코드}.js 파일은 있는데 strings.js 의 AML.LANGS 에 없음 (선택 목록에 안 나옴)
 *   ✗ 파일 없음    : AML.LANGS 에는 있는데 lang/{코드}.js 파일이 없음
 *   ⚠ 영어와 같은 문장 : 오류는 아니지만 번역을 잊었을 수 있어 알려준다
 *   ※ 단복수: 'x.one' 은 언어팩에 'x.other' 가 있으면 빠진 것으로 치지 않는다 (한국어·일본어 등)
 *
 * (2-W) meshmelo 포털 문장 php/mm/web/portal/lang/{코드}.js 도 검사한다
 *   ✗ 빠진 키(아티스트용) · 모르는 키 · 변수 {x} 다름 · HTML 태그 수 다름 · 굵게(**)·화면 이름([[ ]]) 표시 수 다름 · 빈 문장
 *   ✗ 목록 누락/파일 없음 : lang/{코드}.js 와 lang/_list.js 의 MM.HAVE 가 다름, MM.LANGS 15개 밖의 코드
 *   ※ 운영자 화면 키(ops.* · st.*)는 번역하지 않는다 → 한국어만 필수, 다른 언어는 없으면 영어로 보임(오류 아님)
 *   node tools/lang-check.js --portal-keys           번역할 아티스트용 키(영어 원문, 키 순서) → docs/lang-portal-keys.json 다시 만들기
 *   node tools/lang-check.js --portal-template ja    새 포털 언어 ja 의 빈 틀(아티스트용 키, 영어 문장 그대로)을 화면에 출력
 * -----------------------------------------------------------------------------
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..', 'public', '_app');
const LANG_DIR = path.join(ROOT, 'lang');

// 브라우저 흉내를 낸 작은 상자에서 파일을 실행한다
function load(files) {
  const box = { window: {}, navigator: { languages: ['en'] }, console };
  box.window = box;
  vm.createContext(box);
  for (const f of files) {
    try {
      vm.runInContext(fs.readFileSync(f, 'utf8'), box, { filename: f });
    } catch (e) {
      console.error(`✗ ${path.relative(process.cwd(), f)} 를 읽을 수 없습니다 (문법 오류): ${e.message}`);
      const m = String(e.stack || '').match(/:(\d+)/);
      if (m) console.error(`  → ${m[1]}번째 줄 근처를 확인하세요. 따옴표(")·쉼표(,)가 빠진 경우가 많습니다.`);
      return null;
    }
  }
  return box.AML;
}

const vars = (s) => (String(s).match(/\{[^{}\s]+\}/g) || []).sort().join(' ');
const args = process.argv.slice(2);

const base = load([path.join(ROOT, 'strings.js')]);
if (!base) process.exit(1);
const EN = base.strings.en;
const LIST = base.LANGS;

// ── 새 언어 틀 만들기 ───────────────────────────────────────────────────────────
if (args[0] === '--template') {
  const code = String(args[1] || '').toLowerCase();
  if (!/^[a-z]{2,3}(-[a-z0-9]{2,8})?$/.test(code)) {
    console.error('사용법: node tools/lang-check.js --template 언어코드   (예: fr, es, zh-tw)');
    process.exit(1);
  }
  const lines = Object.keys(EN).map((k) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(EN[k]));
  process.stdout.write(
    `// ${code} 언어팩 — 오른쪽 문장만 번역한다. 키(왼쪽)와 {변수}는 그대로 둔다.\n` +
    `// 'xxx.one' / 'xxx.other' 는 단수/복수. 구분이 없는 언어는 .one 줄을 지워도 된다.\n` +
    `AML.addLang('${code}', {\n` + lines.join(',\n') + '\n});\n'
  );
  process.exit(0);
}

// ── 2-W: meshmelo 포털 문장 php/mm/web/portal/lang/{코드}.js ─────────────────────────────────────
// 영어(en.js) 기준. 운영자 화면 키(ops.* · st.*)는 번역하지 않는다(운영자만 봄) → ko 만 필수, 다른 언어는 빠져도 영어로 보임.
const P_DIR = path.join(__dirname, '..', 'php', 'mm', 'web', 'portal', 'lang');
const P_KEYS_FILE = path.join(__dirname, '..', 'docs', 'lang-portal-keys.json');
const P_OPS = /^(ops|st)\./;
const P_FULL = new Set(['ko']);   // 운영자 키까지 필수인 언어
function loadPortal(files) {
  const box = { console };
  box.window = box;
  vm.createContext(box);
  for (const f of files) {
    try { vm.runInContext(fs.readFileSync(f, 'utf8'), box, { filename: f }); } catch (e) {
      console.log(`  ✗ ${path.relative(process.cwd(), f)} 를 읽을 수 없습니다 (문법 오류): ${e.message}`);
      return null;
    }
  }
  return box.MM;
}
const pTags = (s) => (String(s).match(/<\/?[a-z][a-z0-9]*/gi) || []).map((x) => x.toLowerCase()).sort().join(' ');
const pMarks = (s) => `**×${(String(s).match(/\*\*/g) || []).length} [[×${(String(s).match(/\[\[/g) || []).length}`;
function portalArtistKeys(PEN) {
  const o = {};
  for (const k of Object.keys(PEN)) if (!P_OPS.test(k)) o[k] = PEN[k];
  return o;
}
function portalKeysDoc(PEN) {
  const keys = portalArtistKeys(PEN);
  return JSON.stringify({
    _about: 'meshmelo portal (my.meshmelo.com) strings to translate — artist-facing only. English source, in en.js key order. Operator screens (ops.*, st.*) are NOT translated. Generated by: node tools/lang-check.js --portal-keys',
    source: 'php/mm/web/portal/lang/en.js',
    target: 'php/mm/web/portal/lang/{code}.js  (copy the shape of ko.js: MM.addLang(\'{code}\', { … }))',
    rules: ['Keep every key and {placeholder} exactly as is', 'Keep **bold** and [[Button name]] marks; text inside [[ ]] is a Cloudflare screen label — keep it in English', 'No HTML', 'Missing keys are shown in English'],
    languages: ['ja', 'de', 'fr', 'es', 'it', 'pt-br', 'ru', 'tr', 'vi', 'id', 'th', 'hi', 'zh-tw'],
    count: Object.keys(keys).length,
    strings: keys,
  }, null, 2) + '\n';
}
// 포털 번역 범위 파일 · 새 언어 틀 (검사보다 먼저, 화면에 다른 글자 없이)
if (args[0] === '--portal-keys' || args[0] === '--portal-template') {
  const PB = loadPortal([path.join(P_DIR, '_list.js'), path.join(P_DIR, 'en.js')]);
  if (!PB || !PB.strings || !PB.strings.en) process.exit(1);
  const PEN = PB.strings.en;
  const LANGS15 = PB.LANGS || {};
  if (args[0] === '--portal-keys') {
    fs.writeFileSync(P_KEYS_FILE, portalKeysDoc(PEN));
    console.log(`docs/lang-portal-keys.json: 아티스트용 ${Object.keys(portalArtistKeys(PEN)).length}키 (운영자 ${Object.keys(PEN).length - Object.keys(portalArtistKeys(PEN)).length}키 제외)`);
    process.exit(0);
  }
  if (args[0] === '--portal-template') {
    const code = String(args[1] || '').toLowerCase();
    if (!LANGS15[code] || code === 'en') { console.error(`사용법: node tools/lang-check.js --portal-template 코드   (${Object.keys(LANGS15).filter((c) => c !== 'en').join(', ')})`); process.exit(1); }
    const keys = portalArtistKeys(PEN);
    process.stdout.write(`// meshmelo 포털 문장 — ${LANGS15[code]} (${code}). 키(왼쪽)·{변수}·**굵게**·[[화면 이름]] 은 그대로, 오른쪽 문장만 번역. 운영자 화면(ops.*·st.*)은 넣지 않는다(영어로 보임).\n` +
      `window.MM = window.MM || { strings: {} };\nMM.addLang = MM.addLang || function (code, o) { MM.strings[code] = o; };\nMM.addLang('${code}', {\n` +
      Object.keys(keys).map((k) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(keys[k])).join(',\n') + '\n});\n');
    process.exit(0);
  }
}

// ── 검사 ────────────────────────────────────────────────────────────────────────
const files = fs.existsSync(LANG_DIR) ? fs.readdirSync(LANG_DIR).filter((f) => /\.js$/.test(f)) : [];
const codes = files.map((f) => f.replace(/\.js$/, ''));
const only = args[0];
let problems = 0;
const bad = (msg) => { problems++; console.log('  ✗ ' + msg); };

console.log(`영어 원본(strings.js): 문장 ${Object.keys(EN).length}개`);
console.log(`언어 목록(AML.LANGS): ${Object.keys(LIST).join(', ')}\n`);

for (const code of Object.keys(LIST)) {
  if (code !== 'en' && !codes.includes(code) && (!only || only === code)) {
    console.log(`[${code}]`); bad(`public/_app/lang/${code}.js 파일이 없습니다. (방문자가 고르면 영어로 보입니다)`);
  }
}

for (const code of codes) {
  if (only && only !== code) continue;
  console.log(`[${code}] public/_app/lang/${code}.js`);
  const before = problems;
  const AML = load([path.join(ROOT, 'strings.js'), path.join(LANG_DIR, code + '.js')]);
  if (!AML) { problems++; continue; }
  const tb = AML.strings[code];
  if (!tb) { bad(`AML.addLang('${code}', …) 가 없습니다. 첫 줄의 언어 코드가 파일 이름과 같은지 확인하세요.`); continue; }
  if (!LIST[code]) bad(`strings.js 의 AML.LANGS 에 ${code} 가 없습니다 → 선택 목록에 나오지 않습니다. 예: ${code}: '언어 이름'`);

  const missing = Object.keys(EN).filter((k) => tb[k] == null && !(/\.one$/.test(k) && tb[k.replace(/\.one$/, '.other')] != null));
  const unknown = Object.keys(tb).filter((k) => EN[k] == null && !/\.(zero|two|few|many|other)$/.test(k));
  missing.forEach((k) => bad(`빠진 키: "${k}"  (영어: ${JSON.stringify(EN[k])})`));
  unknown.forEach((k) => bad(`모르는 키: "${k}"  (영어에 없는 키입니다. 키 이름을 바꾸지 않았는지 확인)`));
  for (const k of Object.keys(tb)) {
    const v = tb[k];
    if (typeof v !== 'string' || !v.trim()) { bad(`빈 문장: "${k}"`); continue; }
    const enKey = EN[k] != null ? k : k.replace(/\.\w+$/, '.other'); // 단복수 변형은 .other 와 비교
    if (EN[enKey] != null && vars(v) !== vars(EN[enKey])) {
      bad(`변수 다름: "${k}"  영어 ${vars(EN[enKey]) || '(변수 없음)'} / 이 언어 ${vars(v) || '(변수 없음)'}`);
    }
  }
  // 참고(오류 아님): 영어와 똑같은 문장 — 번역을 잊었을 수 있다. 숫자·이름처럼 같아도 되는 것도 있다.
  const same = Object.keys(tb).filter((k) => EN[k] != null && tb[k] === EN[k] && /[a-z]{3}/i.test(EN[k]));
  if (same.length) console.log(`  ⚠ 영어와 같은 문장 ${same.length}개 (번역을 잊었는지 확인): ${same.slice(0, 8).join(', ')}${same.length > 8 ? ' …' : ''}`);
  const done = Object.keys(EN).length - missing.length;
  console.log(`  번역 ${done}/${Object.keys(EN).length} (${Math.floor(done / Object.keys(EN).length * 100)}%)` + (problems === before ? ' ✓' : ''));
}

// ── 3-10: 관리 화면 전용 문장 public/_app/lang-admin/{코드}.js (방문자 화면은 받지 않는다) ──────────────
// 3-12: 관리 화면은 en·ko·ja 가 필수, 나머지 언어는 빠진 문장이 영어로 보이는 것이 정한 방식(GPT 가 나중에 번역)이라
//       빠진 키를 ⚠ 알림으로만 센다. 모르는 키·변수 다름·빈 문장은 어느 언어든 오류.
const ADMIN_REQUIRED = new Set(['ko', 'ja']);
const ADMIN_DIR = path.join(ROOT, 'lang-admin');
if (fs.existsSync(path.join(ADMIN_DIR, 'en.js'))) {
  const baseA = load([path.join(ROOT, 'strings.js'), path.join(ADMIN_DIR, 'en.js')]);
  if (!baseA) problems++;
  else {
    const AEN = {};
    for (const k of Object.keys(baseA.strings.en)) if (EN[k] == null) AEN[k] = baseA.strings.en[k];
    const dup = Object.keys(baseA.strings.en).filter((k) => EN[k] != null && baseA.strings.en[k] !== EN[k]);
    console.log(`\n관리 전용(lang-admin/en.js): 문장 ${Object.keys(AEN).length}개`);
    dup.forEach((k) => bad(`lang-admin/en.js 의 "${k}" 가 strings.js 와 겹칩니다 (한 곳에만 두세요)`));
    for (const code of Object.keys(LIST)) {
      if (code === 'en' || (only && only !== code)) continue;
      const f = path.join(ADMIN_DIR, code + '.js');
      console.log(`[${code}] public/_app/lang-admin/${code}.js`);
      if (!fs.existsSync(f)) { bad(`public/_app/lang-admin/${code}.js 파일이 없습니다. (관리 화면 새 문장이 영어로 보입니다)`); continue; }
      const before = problems;
      const A = load([path.join(ROOT, 'strings.js'), f]);
      if (!A) { problems++; continue; }
      const tb = A.strings[code] || {};
      const keys = Object.keys(tb);
      const missing = Object.keys(AEN).filter((k) => tb[k] == null && !(/\.one$/.test(k) && tb[k.replace(/\.one$/, '.other')] != null));
      if (ADMIN_REQUIRED.has(code)) missing.forEach((k) => bad(`빠진 키: "${k}"  (영어: ${JSON.stringify(AEN[k])})`));
      else if (missing.length) console.log(`  ⚠ 아직 번역 안 된 관리 문장 ${missing.length}개 (영어로 보임 — 오류 아님): ${missing.slice(0, 6).join(', ')}${missing.length > 6 ? ' …' : ''}`);
      keys.filter((k) => AEN[k] == null && !/\.(zero|two|few|many|other)$/.test(k)).forEach((k) => bad(`모르는 키: "${k}"`));
      for (const k of keys) {
        const v = tb[k];
        if (typeof v !== 'string' || !v.trim()) { bad(`빈 문장: "${k}"`); continue; }
        const enKey = AEN[k] != null ? k : k.replace(/\.\w+$/, '.other');
        if (AEN[enKey] != null && vars(v) !== vars(AEN[enKey])) bad(`변수 다름: "${k}"  영어 ${vars(AEN[enKey]) || '(변수 없음)'} / 이 언어 ${vars(v) || '(변수 없음)'}`);
      }
      const done = Object.keys(AEN).length - missing.length;
      console.log(`  번역 ${done}/${Object.keys(AEN).length}` + (problems === before ? ' ✓' : ''));
    }
  }
}

if (fs.existsSync(path.join(P_DIR, 'en.js'))) {
  const PB = loadPortal([path.join(P_DIR, '_list.js'), path.join(P_DIR, 'en.js')]);
  if (!PB || !PB.strings || !PB.strings.en) { problems++; }
  else {
    const PEN = PB.strings.en;
    const LANGS15 = PB.LANGS || {};
    const HAVE = PB.HAVE || [];
    const pFiles = fs.readdirSync(P_DIR).filter((f) => /^[a-z]{2,3}(-[a-z0-9]{2,8})?\.js$/.test(f)).map((f) => f.replace(/\.js$/, ''));
    const artist = portalArtistKeys(PEN);
    console.log(`\nmeshmelo 포털(php/mm/web/portal/lang/en.js): 문장 ${Object.keys(PEN).length}개 = 아티스트용 ${Object.keys(artist).length} + 운영자(ops.*·st.*) ${Object.keys(PEN).length - Object.keys(artist).length}`);
    console.log(`포털 언어 목록 HAVE: ${HAVE.join(', ')}  (받을 수 있는 언어 ${Object.keys(LANGS15).length}개)`);
    if (!HAVE.includes('en')) bad('lang/_list.js 의 MM.HAVE 에 en 이 없습니다');
    for (const c of HAVE) if (!pFiles.includes(c)) bad(`MM.HAVE 에 ${c} 가 있는데 php/mm/web/portal/lang/${c}.js 파일이 없습니다`);
    for (const c of HAVE) if (!LANGS15[c]) bad(`MM.HAVE 의 ${c} 가 MM.LANGS(15개)에 없습니다`);
    for (const c of pFiles) {
      if (!LANGS15[c]) bad(`portal/lang/${c}.js: ${c} 는 MM.LANGS(15개) 밖의 코드입니다`);
      else if (!HAVE.includes(c)) bad(`portal/lang/${c}.js 파일이 있는데 lang/_list.js 의 MM.HAVE 에 없습니다 → 목록에 안 보입니다 (빌드는 저절로 넣지만 원본도 고치세요)`);
    }
    for (const code of pFiles) {
      if (code === 'en' || (only && only !== code)) continue;
      console.log(`[${code}] php/mm/web/portal/lang/${code}.js`);
      const before = problems;
      const P = loadPortal([path.join(P_DIR, '_list.js'), path.join(P_DIR, 'en.js'), path.join(P_DIR, code + '.js')]);
      if (!P) { problems++; continue; }
      const tb = P.strings[code];
      if (!tb) { bad(`MM.addLang('${code}', …) 가 없습니다. 언어 코드가 파일 이름과 같은지 확인하세요.`); continue; }
      const need = P_FULL.has(code) ? PEN : artist;
      const missing = Object.keys(need).filter((k) => tb[k] == null);
      // M-4: 영어·한국어(P_FULL)는 모든 키가 있어야 한다. 그 밖의 언어에 아직 없는 새 문장은 t() 가 영어로 보여 주므로 경고만 (관리 화면 문장과 같은 방식 — GPT 번역 묶음 때 채움)
      if (P_FULL.has(code)) missing.forEach((k) => bad(`빠진 키: "${k}"  (영어: ${JSON.stringify(PEN[k]).slice(0, 80)})`));
      else if (missing.length) console.log(`  ⚠ 아직 번역 안 된 문장 ${missing.length}개 (영어로 보임 — 오류 아님): ${missing.slice(0, 6).join(', ')}${missing.length > 6 ? ' …' : ''}`);
      Object.keys(tb).filter((k) => PEN[k] == null).forEach((k) => bad(`모르는 키: "${k}"`));
      for (const k of Object.keys(tb)) {
        const v = tb[k];
        if (PEN[k] == null) continue;
        if (typeof v !== 'string' || !v.trim()) { bad(`빈 문장: "${k}"`); continue; }
        if (vars(v) !== vars(PEN[k])) bad(`변수 다름: "${k}"  영어 ${vars(PEN[k]) || '(변수 없음)'} / 이 언어 ${vars(v) || '(변수 없음)'}`);
        if (pTags(v) !== pTags(PEN[k])) bad(`HTML 태그 다름: "${k}"  영어 ${pTags(PEN[k]) || '(없음)'} / 이 언어 ${pTags(v) || '(없음)'}`);
        if (pMarks(v) !== pMarks(PEN[k])) bad(`표시 수 다름: "${k}"  영어 ${pMarks(PEN[k])} / 이 언어 ${pMarks(v)}`);
      }
      const opsLeft = P_FULL.has(code) ? 0 : Object.keys(PEN).filter((k) => P_OPS.test(k) && tb[k] == null).length;
      const same = Object.keys(tb).filter((k) => PEN[k] != null && tb[k] === PEN[k] && /[a-z]{3}/i.test(PEN[k]) && !P_OPS.test(k));
      if (same.length) console.log(`  ⚠ 영어와 같은 문장 ${same.length}개 (번역을 잊었는지 확인): ${same.slice(0, 8).join(', ')}${same.length > 8 ? ' …' : ''}`);
      const done = Object.keys(need).length - missing.length;
      console.log(`  번역 ${done}/${Object.keys(need).length}` + (opsLeft ? ` (운영자 키 ${opsLeft}개는 영어 — 정한 방식)` : '') + (problems === before ? ' ✓' : ''));
    }
    // 번역 범위 파일이 en.js 와 맞는지 (오류 아님 — 다시 만들기 안내)
    const doc = fs.existsSync(P_KEYS_FILE) ? fs.readFileSync(P_KEYS_FILE, 'utf8') : '';
    if (doc !== portalKeysDoc(PEN)) console.log('  ⚠ docs/lang-portal-keys.json 이 en.js 와 다릅니다 → node tools/lang-check.js --portal-keys');
  }
}

console.log(problems ? `\n문제 ${problems}개. 위 ✗ 줄을 고친 뒤 다시 실행하세요.` : '\n모두 정상입니다.');
process.exit(problems ? 1 : 0);
